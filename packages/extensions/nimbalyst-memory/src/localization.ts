const listeners = new Set<() => void>();
let localeObserver: MutationObserver | null = null;

function getLocale(): 'en' | 'ja' {
  return typeof document !== 'undefined' && document.documentElement.lang.toLowerCase().startsWith('ja')
    ? 'ja'
    : 'en';
}

function subscribeLocale(listener: () => void): () => void {
  listeners.add(listener);
  if (!localeObserver && typeof document !== 'undefined' && typeof MutationObserver !== 'undefined') {
    localeObserver = new MutationObserver(() => listeners.forEach((notify) => notify()));
    localeObserver.observe(document.documentElement, { attributes: true, attributeFilter: ['lang'] });
  }
  return () => {
    listeners.delete(listener);
    if (listeners.size === 0) {
      localeObserver?.disconnect();
      localeObserver = null;
    }
  };
}

function interpolate(template: string, values?: MemoryTextValues): string {
  return template.replace(/\{\{(\w+)\}\}/g, (_, key: string) => String(values?.[key] ?? ''));
}

export function useMemoryText() {
  const locale = useSyncExternalStore(subscribeLocale, getLocale, () => 'en');
  return useCallback(
    (key: MemoryTextKey, values?: MemoryTextValues) => interpolate((locale === 'ja' ? ja : en)[key], values),
    [locale]
  );
}

export type { MemoryTextKey, MemoryTextValues };
